"""
User accounts for the server: login ID and password generated by the server.

    <data_dir>/users.json      accounts (password hash only, never the password)
    <data_dir>/sessions.json   logged-in sessions (hash of the session token)

The administrator creates accounts on the server (rax-server user add, or
sudo bash deploy/install.sh user add); the server makes up the login ID and
a random password and shows them once.  A client logs in with them and gets
a session token, which it keeps instead of the password.

Passwords are stored as PBKDF2-SHA256 hashes.  Resetting a password or
disabling / removing an account ends that user's sessions at once, also
while the server is running (the files are re-read when they change).
"""

import hashlib
import json
import os
import re
import secrets
import threading
import time
from typing import Dict, List, Optional, Tuple

ITERATIONS = 200_000
SESSION_DAYS = float(os.environ.get('RAX_SESSION_DAYS', '30'))
MAX_FAILS = 5                     # wrong passwords in a row ...
LOCK_SECONDS = 60                 # ... lock the login ID for this long
_UID_RE = re.compile(r'^[a-z][a-z0-9._-]{2,31}$')
# no 0/O, 1/l/I: easy to read out and type
_PW_CHARS = 'abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'


class UserError(ValueError):
    pass


def new_password() -> str:
    """12 random characters in three groups, e.g. 'k7Pq-9mXt-3vRw'."""
    return '-'.join(''.join(secrets.choice(_PW_CHARS) for _ in range(4)) for _ in range(3))


def _hash(password: str, salt: bytes) -> str:
    return hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, ITERATIONS).hex()


def _token_key(token: str) -> str:
    return hashlib.sha256(token.encode('utf-8')).hexdigest()


class _JsonFile:
    """A small JSON file, re-read when another process changes it."""

    def __init__(self, path: str):
        self.path = path
        self._mtime = None
        self.data: Dict[str, dict] = {}

    def load(self) -> Dict[str, dict]:
        try:
            m = os.stat(self.path).st_mtime_ns
        except FileNotFoundError:
            self._mtime, self.data = None, {}
            return self.data
        if m != self._mtime:
            try:
                with open(self.path, encoding='utf-8') as f:
                    self.data = json.load(f)
            except (OSError, ValueError):
                self.data = {}
            self._mtime = m
        return self.data

    def save(self) -> None:
        os.makedirs(os.path.dirname(self.path) or '.', exist_ok=True)
        tmp = f'{self.path}.{os.getpid()}.tmp'
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            json.dump(self.data, f, indent=1)
        os.replace(tmp, self.path)
        self._mtime = os.stat(self.path).st_mtime_ns


class UserStore:
    def __init__(self, data_dir: str):
        self._users = _JsonFile(os.path.join(data_dir, 'users.json'))
        self._sessions = _JsonFile(os.path.join(data_dir, 'sessions.json'))
        self._lock = threading.Lock()
        self._fails: Dict[str, Tuple[int, float]] = {}

    # ── accounts (administrator, on the server) ──────────────────────────
    def has_users(self) -> bool:
        with self._lock:
            return bool(self._users.load())

    def list(self) -> List[dict]:
        with self._lock:
            users = self._users.load()
            return [{'uid': u, 'name': d.get('name', ''), 'admin': bool(d.get('admin')),
                     'enabled': d.get('enabled', True), 'created': d.get('created'),
                     'last_login': d.get('last_login')} for u, d in sorted(users.items())]

    def add(self, uid: str = '', name: str = '', admin: bool = False) -> Tuple[str, str]:
        """Create an account. Returns (login ID, password); the password is not kept."""
        with self._lock:
            users = self._users.load()
            uid = (uid or '').strip().lower()
            if uid:
                if not _UID_RE.match(uid):
                    raise UserError('Login ID: 3-32 characters, a-z 0-9 . _ -, '
                                    'starting with a letter')
                if uid in users:
                    raise UserError(f'Login ID {uid} already exists')
            else:
                while True:
                    uid = 'rx' + ''.join(secrets.choice('0123456789') for _ in range(5))
                    if uid not in users:
                        break
            password = new_password()
            users[uid] = {'name': name.strip(), 'admin': bool(admin), 'enabled': True,
                          'created': time.time(), 'epoch': 1, **self._pw_fields(password)}
            self._users.save()
            return uid, password

    def reset(self, uid: str) -> str:
        """New password; the user's sessions end."""
        with self._lock:
            d = self._get(uid)
            password = new_password()
            d.update(self._pw_fields(password))
            d['epoch'] = d.get('epoch', 1) + 1
            self._users.save()
            return password

    def set_enabled(self, uid: str, enabled: bool) -> None:
        with self._lock:
            d = self._get(uid)
            d['enabled'] = bool(enabled)
            d['epoch'] = d.get('epoch', 1) + 1
            self._users.save()

    def remove(self, uid: str) -> None:
        with self._lock:
            self._get(uid)
            del self._users.data[uid.strip().lower()]
            self._users.save()

    def _get(self, uid: str) -> dict:
        users = self._users.load()
        d = users.get((uid or '').strip().lower())
        if d is None:
            raise UserError(f'No login ID {uid}')
        return d

    @staticmethod
    def _pw_fields(password: str) -> dict:
        salt = secrets.token_bytes(16)
        return {'salt': salt.hex(), 'hash': _hash(password, salt)}

    # ── login (clients) ──────────────────────────────────────────────────
    def login(self, uid: str, password: str) -> dict:
        """Check the password and open a session. Raises UserError."""
        uid = (uid or '').strip().lower()
        n, until = self._fails.get(uid, (0, 0.0))
        if until > time.time():
            raise UserError(f'Too many wrong passwords: try again in '
                            f'{int(until - time.time()) + 1} s')
        with self._lock:
            d = self._users.load().get(uid)
        ok = bool(d) and secrets.compare_digest(
            _hash(password or '', bytes.fromhex(d['salt'])), d['hash'])
        if not ok:
            n += 1
            self._fails[uid] = (0, time.time() + LOCK_SECONDS) if n >= MAX_FAILS else (n, 0.0)
            raise UserError('Wrong login ID or password')
        if not d.get('enabled', True):
            raise UserError('This login ID is disabled; ask the administrator')
        self._fails.pop(uid, None)
        token = secrets.token_urlsafe(32)
        expires = time.time() + SESSION_DAYS * 86400
        with self._lock:
            sessions = self._sessions.load()
            now = time.time()
            for k in [k for k, s in sessions.items() if s.get('expires', 0) < now]:
                del sessions[k]                     # tidy up expired ones
            sessions[_token_key(token)] = {'uid': uid, 'epoch': d.get('epoch', 1),
                                           'expires': expires}
            self._sessions.save()
            users = self._users.load()
            if uid in users:
                users[uid]['last_login'] = now
                self._users.save()
        return {'token': token, 'uid': uid, 'name': d.get('name', ''),
                'admin': bool(d.get('admin')), 'expires': expires}

    def session(self, token: str) -> Optional[dict]:
        """The user of a session token, or None (unknown, expired, reset or disabled)."""
        if not token:
            return None
        with self._lock:
            s = self._sessions.load().get(_token_key(token))
            if not s or s.get('expires', 0) < time.time():
                return None
            d = self._users.load().get(s['uid'])
        if not d or not d.get('enabled', True) or d.get('epoch', 1) != s.get('epoch'):
            return None
        return {'uid': s['uid'], 'name': d.get('name', ''), 'admin': bool(d.get('admin'))}

    def logout(self, token: str) -> None:
        with self._lock:
            sessions = self._sessions.load()
            if sessions.pop(_token_key(token or ''), None) is not None:
                self._sessions.save()
